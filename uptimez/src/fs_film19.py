def lipstick_word(c, x, y, size, n):
    """STUPID, in lipstick: fat, crooked capitals, each a little off its line; the first n letters."""
    c.select_font_face("Lilita One", cairo.FONT_SLANT_NORMAL, cairo.FONT_WEIGHT_NORMAL)
