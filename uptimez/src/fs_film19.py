def _backout(u):
    """0..1 with a small dip first (anticipation) and an overshoot that settles."""
    u = min(1.0, max(0.0, u))
    if u < 0.18:
        return -0.07 * math.sin(math.pi * u / 0.18)
    v = (u - 0.18) / 0.82
    c1, c3 = 1.70158, 2.70158
    return 1 + c3 * (v - 1) ** 3 + c1 * (v - 1) ** 2


def tween(keys, t, dur=0.36, plain=False):
    """keys: [(time, value or tuple)]. The value at t: each key eased in from the one before it over `dur`."""
    val = keys[0][1]
    for (t0, v0), (t1, v1) in zip(keys, keys[1:]):
        if t < t1:
            break
        u = (t - t1) / dur
        w = ease(u) if plain else _backout(u)
        prev = val
        val = tuple(a + (b_ - a) * w for a, b_ in zip(prev, v1)) if isinstance(v1, tuple) else prev + (v1 - prev) * w
        if u < 1:
            break
    return val


