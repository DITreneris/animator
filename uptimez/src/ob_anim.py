def _badge_text(orig):
    """kit.text, noting every name badge it writes: where (design pixels) and, for the checker, the letters themselves
    as a mask in device pixels. With OPT["mark"] the name is written in magenta, so the checker can find, by comparing
    two renders, which of its letters are actually seen."""
    def text(k, s_, x, y, size, *a, **kw):
        if s_ not in BADGE_NAMES or BASE[0] is None:
            return orig(k, s_, x, y, size, *a, **kw)
        c = k.c
        font = kw.get("font", a[1] if len(a) > 1 else kit.FONT)
        bold = kw.get("bold", a[2] if len(a) > 2 else False)
        rot = kw.get("rot", a[4] if len(a) > 4 else 0.0)
        c.save(); c.translate(x, y); c.rotate(rot)
        c.select_font_face(font, 0, 1 if bold else 0); c.set_font_size(size)
        e = c.text_extents(s_); hw, hh = e.width / 2 + 0.12 * size, e.height / 2 + 0.10 * size
        corners = ((-hw, -hh), (hw, -hh), (hw, hh), (-hw, hh))
        dev = [c.user_to_device(px, py) for px, py in corners]
        x0, y0 = int(math.floor(min(d[0] for d in dev))) - 1, int(math.floor(min(d[1] for d in dev))) - 1
        w = int(math.ceil(max(d[0] for d in dev))) + 2 - x0; h = int(math.ceil(max(d[1] for d in dev))) + 2 - y0
        mask = None
        if OPT["mark"] and w < 2000 and h < 2000:
            ms = cairo.ImageSurface(cairo.FORMAT_A8, w, h); mc = cairo.Context(ms)
            mc.set_matrix(c.get_matrix() * cairo.Matrix(x0=-x0, y0=-y0))
            mc.select_font_face(font, 0, 1 if bold else 0); mc.set_font_size(size)
            mc.move_to(-e.width / 2 - e.x_bearing, e.height / 2); mc.show_text(s_); ms.flush()
            mask = (np.frombuffer(ms.get_data(), np.uint8).reshape(h, ms.get_stride())[:, :w] > 128).copy()
        QA["badges"].append(dict(name=s_, quad=[D(k, px, py) for px, py in corners], x0=x0, y0=y0, mask=mask))
        c.restore()
        if OPT["mark"]:
            kw = dict(kw); a = list(a)
            if a:
                a[0] = (1.0, 0.0, 1.0)
            else:
                kw["col"] = (1.0, 0.0, 1.0)
        return orig(k, s_, x, y, size, *a, **kw)
    return text


