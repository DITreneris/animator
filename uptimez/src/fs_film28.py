class swell:
    """v16: breathing you can see. The body, drawn inside this, swells from its feet: 1% taller and 0.6% wider at
    the top of the breath. fix(o) moves the head and hands it returns to where they were drawn."""
    def __init__(self, k, x, feet, name, on=True):
        b_ = breath(name) if on and not sb._DRY[0] else 0.0
        self.k, self.x, self.f, self.sx, self.sy = k, x, feet, 1 + 0.006 * b_, 1 + 0.010 * b_

    def __enter__(self):
        c = self.k.c
        c.save(); c.translate(self.x, self.f); c.scale(self.sx, self.sy); c.translate(-self.x, -self.f)
        return self

    def __exit__(self, *e):
        self.k.c.restore()

    def fix(self, o):
        if not isinstance(o, dict):
            return o
        o = dict(o)
        m = lambda p: (self.x + (p[0] - self.x) * self.sx, self.f + (p[1] - self.f) * self.sy)
        for key in ("head", "screen"):
            if o.get(key):
                o[key] = m(o[key])
        if o.get("hands"):
            o["hands"] = [m(h) for h in o["hands"]]
        return o


