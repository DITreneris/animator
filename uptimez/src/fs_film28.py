def loop_end(k):
    """U's last two beats (v27): the opening's own drawing at its frame 0, so the film's last frame IS its first (but
    the calendar). The clocks run backwards to zero at the cut, so his breath, his curl and the page's corner arrive
    where frame 0 starts. In the last beat the portrait trembles, and is still for the last tenth."""
    tb, T = CUR_T[0], SHOT_T[0]
    end = SHOT_OFF.get("shake", 0.0) + 0.35
    shake = CUR_BEAT[0] == "shake"
    LOOP_WOB[0] = 0.07 * math.sin(2 * math.pi * 8 * tb) * max(0.0, 1 - tb / 0.24) if shake else 0.0
    CUR_T[0] = 0.0; SHOT_T[0] = T - end
    try:
        opening(k)
    finally:
        CUR_T[0] = tb; SHOT_T[0] = T; LOOP_WOB[0] = 0.0


